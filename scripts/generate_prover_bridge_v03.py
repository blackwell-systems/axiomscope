#!/usr/bin/env python3
"""Generate a prover-side check against elaborated Isabelle/ZF theorem propositions.

The registered theorem headers remain a *candidate* interpretation. The
generated Isabelle/ML code checks them against actual theorem objects
before any exported evidence is trusted. This does not reveal proof-term
dependencies or prove logical independence.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts import foundation_probe_v02 as probe

MANIFEST = ROOT / "research/gates/b/manifest.json"
OUTPUT = ROOT / "research/gates/b/GateB_ProverBridge.ML"


def proposition(text: str) -> str:
    if not text or '"' in text or "\n" in text or "\r" in text:
        raise ValueError("Unsupported quoted Isabelle proposition")
    return '@{prop "' + text + '"}'


def generate() -> str:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    _, signatures = probe.checked_claims(manifest)
    checks = []
    for contract in probe.CONTRACTS:
        sig = signatures[contract.claim_id]
        premises = "[" + ", ".join(proposition(p) for p in sig.premises) + "]"
        checks.append(
            "    certify ("
            + json.dumps(contract.claim_id) + ",\n"
            + "      @{thm " + contract.theorem + "},\n"
            + "      " + premises + ",\n"
            + "      " + proposition(sig.conclusion) + ")"
        )
    return (
        "(* GENERATED by scripts/generate_prover_bridge_v03.py; do not hand-edit. *)\n"
        "val thy = @{theory};\n"
        "val ctxt = @{context};\n"
        "fun certify (id, theorem, prems, concl) =\n"
        "  let\n"
        "    val actual = Thm.prop_of theorem;\n"
        "    val expected = Logic.list_implies (prems, concl);\n"
        "    val observed_prems = Thm.prems_of theorem;\n"
        "    val valid = Pattern.matches thy (actual, expected);\n"
        "    val _ = if valid andalso length observed_prems = length prems then ()\n"
        "      else error (\"AxiomScope: elaborated theorem mismatches source declaration: \" ^ id);\n"
        "    fun flat s = String.translate\n"
        "      (fn #\"\\n\" => \" \" | #\"\\t\" => \" \" | c => str c) s;\n"
        "    val pretty_prems = map (flat o Syntax.string_of_term ctxt) observed_prems;\n"
        "    val pretty_concl = flat (Syntax.string_of_term ctxt (Thm.concl_of theorem));\n"
        "  in\n"
        "    id ^ \"\\t\" ^ Int.toString (length observed_prems) ^ \"\\t\" ^\n"
        "    String.concatWith \" || \" pretty_prems ^ \"\\t\" ^ pretty_concl\n"
        "  end;\n"
        "val rows = [\n" + ",\n".join(checks) + "\n  ];\n"
        "val exported = String.concatWith \"\\n\" rows ^ \"\\n\";\n"
        "val _ = Export.export thy\n"
        "  (Path.binding (Path.basic \"axiomscope_theorems.tsv\", Position.none))\n"
        "  (Bytes.contents_blob (Bytes.string exported));\n"
        "val _ = writeln \"AXIOMSCOPE_PROVER_BRIDGE_CERTIFIED\";\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--check", action="store_true")
    action.add_argument("--write", action="store_true")
    args = parser.parse_args()
    try:
        expected = generate()
        if args.check:
            if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
                raise ValueError("Isabelle prover bridge drift (run --write and commit)")
            print("Prover bridge source matches registered Isabelle theorem headers")
        else:
            OUTPUT.write_text(expected, encoding="utf-8")
            print("Regenerated", OUTPUT)
        return 0
    except (OSError, ValueError, KeyError) as e:
        print("Prover bridge generation FAILED:", e, file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
